"""End-to-end demonstration: produces real DXF drawings and validation reports
under examples/output/. Run:  python examples/run_demo.py"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "tests"))  # reuse the dependency-free PDF writer

from agentcad.policy import Policy  # noqa: E402
from agentcad.service import Runtime  # noqa: E402
from conftest import write_pdf  # noqa: E402

OUT = HERE / "output"
MARKER = OUT / ".agentcad-demo"


def save(name: str, obj) -> None:
    (OUT / name).write_text(json.dumps(obj, indent=1, ensure_ascii=False, default=str), "utf-8")


def must(r: dict) -> dict:
    if not r["ok"]:
        raise SystemExit(json.dumps(r["error"], indent=1, ensure_ascii=False))
    return r


def main() -> None:
    if OUT.exists() and any(OUT.iterdir()):
        if not MARKER.exists():
            raise SystemExit(f"{OUT} exists and was not created by this demo; refusing to delete it")
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True, exist_ok=True)
    MARKER.write_text("generated by examples/run_demo.py\n")
    rt = Runtime(Policy(root=OUT))
    summary = {}

    # --- Test A: spec -> dimensioned drawing on an A4 sheet with title block -------------------
    spec = {"kind": "plate", "units": "mm", "name": "Mounting plate", "width": 100, "height": 60,
            "holes": [{"pattern": "corners", "diameter": 8, "edge_offset": 10}], "material": "Q235", "thickness": 3,
            "sheet": "A4", "title_block": {"DWG_NO": "AC-PL-001", "DRAWN_BY": "agentcad", "DATE": "2026-10-26"}}
    a = must(rt.draw_from_spec(spec, "A_mounting_plate_100x60.dxf"))
    save("A_validation.json", a["validation"])
    must(rt.export_drawing("A_mounting_plate_100x60.dxf", "A_mounting_plate_100x60.svg", "svg"))
    must(rt.export_drawing("A_mounting_plate_100x60.dxf", "A_mounting_plate_100x60_R12.dxf", "dxf", "R12"))
    summary["A"] = {"passed": a["validation"]["passed"], **a["validation"]["summary"]}

    # --- Test B: revise width to 120 mm, holes keep 10 mm edge distance ---------------------------
    must(rt.draw_from_spec(spec, "B_mounting_plate.dxf"))
    must(rt.export_drawing("B_mounting_plate.dxf", "B_mounting_plate_rev0_100x60.dxf", "dxf"))
    b = must(rt.revise_drawing("B_mounting_plate.dxf", {"width": 120}))
    d = must(rt.get_diff("B_mounting_plate.dxf"))
    save("B_validation.json", b["validation"])
    save("B_diff.json", {k: d[k] for k in ("against", "summary", "added", "deleted", "modified")})
    must(rt.export_drawing("B_mounting_plate.dxf", "B_mounting_plate_rev1_120x60.svg", "svg"))
    summary["B"] = {"passed": b["validation"]["passed"], "diff": d["summary"], **b["validation"]["summary"]}

    # --- Test C: technical documents (PDF + Chinese Markdown) -> drawing ---------------------------
    write_pdf(OUT / "C_bracket_spec.pdf", [
        ["BRACKET PLATE BP-150 - TECHNICAL SPECIFICATION", "1 Scope", "This document defines the bracket plate.",
         "All dimensions are in mm."],
        ["2 Geometry", "Overall size 150 x 90 mm.", "Thickness 5 mm.", "3 Holes",
         "Four through holes, diameter 9 mm, located at each corner,", "15 mm from the adjacent edges.",
         "4 Material", "Material: S355"]])
    c = must(rt.revise_from_document("C_bracket_spec.pdf", "C_bracket_from_pdf.dxf"))
    save("C_pdf_trace.json", {k: c[k] for k in ("spec", "traceability", "verification", "issues")})
    shutil.copy(HERE.parent / "tests" / "fixtures" / "plate_spec_zh.md", OUT / "C_plate_spec_zh.md")
    cz = must(rt.revise_from_document("C_plate_spec_zh.md", "C_plate_from_zh_md.dxf"))
    save("C_zh_trace.json", {k: cz[k] for k in ("spec", "traceability", "verification", "issues")})
    must(rt.export_drawing("C_plate_from_zh_md.dxf", "C_plate_from_zh_md.svg", "svg"))
    shutil.copy(HERE.parent / "tests" / "fixtures" / "plate_spec_conflict.txt", OUT / "C_conflict.txt")
    cc = rt.revise_from_document("C_conflict.txt", "C_conflict.dxf")
    save("C_conflict_refusal.json", cc)
    summary["C"] = {"pdf_passed": c["validation"]["passed"], "zh_passed": cz["validation"]["passed"],
                    "conflict_refused": not cc["ok"], "conflict_code": cc.get("error", {}).get("code")}

    # --- Test E: tamper with a copy behind the runtime's back, validator must notice --------------
    import ezdxf
    from agentcad.model import get_tag
    must(rt.export_drawing("A_mounting_plate_100x60.dxf", "E_tampered.dxf", "dxf"))
    doc = ezdxf.readfile(str(OUT / "E_tampered.dxf"))
    for e in list(doc.modelspace()):
        if get_tag(e) == "hole.tr":
            e.translate(1.5, 0, 0)
        if get_tag(e) == "dim.width":
            doc.modelspace().delete_entity(e)
    doc.saveas(OUT / "E_tampered.dxf")
    e_rep = must(rt.validate_drawing("E_tampered.dxf"))["validation"]
    save("E_tamper_validation.json", e_rep)
    summary["E"] = {"passed": e_rep["passed"],
                    "failed": [r["id"] for r in e_rep["requirements"] if r["status"] != "pass"]}

    # --- optional AutoCAD backend: DWG deliverables and AutoCAD's own AUDIT verdict ------------
    from agentcad.backends.autocad import find_accoreconsole
    if find_accoreconsole() is not None:
        acad = {}
        for name in ("A_mounting_plate_100x60.dxf", "B_mounting_plate.dxf", "C_bracket_from_pdf.dxf",
                     "C_plate_from_zh_md.dxf", "A_mounting_plate_100x60_R12.dxf"):
            a = must(rt.autocad_audit(name))
            acad[name] = {"passed": a["passed"], "audit_errors": a["audit_errors"],
                          "entities_seen_by_autocad": a["entities_seen_by_autocad"]}
        for name in ("A_mounting_plate_100x60", "B_mounting_plate"):
            d = must(rt.export_drawing(f"{name}.dxf", f"{name}.dwg", "dwg"))
            acad[f"{name}.dwg"] = {"bytes": d["bytes"], "readback": d["readback"]}
        save("AUTOCAD_checks.json", acad)
        summary["autocad"] = {k: v.get("passed", v.get("readback", {}).get("readable")) for k, v in acad.items()}
    else:
        summary["autocad"] = "skipped: AutoCAD backend not installed"

    summary["metrics"] = {k: v for k, v in must(rt.get_metrics()).items() if k != "calls"}
    save("SUMMARY.json", summary)
    print(json.dumps(summary, indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
